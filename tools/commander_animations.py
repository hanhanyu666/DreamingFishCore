def payload(name: str) -> dict:
    """转成 NeoForge 的动画 JSON。数值按 Java 模型语义原样写出，不做取反。"""
    anim = ANIMATIONS[name]
    out = {"length": anim["length"], "loop": anim["loop"], "animations": []}
    for bone, (channel, keys) in anim["tracks"]:
        keyframes = []
        for t, x, y, z in keys:
            keyframes.append({
                "timestamp": t,
                "target": [float(x), float(y), float(z)],
                "interpolation": "minecraft:linear",
            })
        out["animations"].append({
            "bone": bone, "target": f"minecraft:{channel}", "keyframes": keyframes,
        })
    return out


def write_all(out_dir: str) -> list[str]:
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for name in ANIMATIONS:
        path = os.path.join(out_dir, f"{name}.json")
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(payload(name), fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        written.append(path)
    return written
