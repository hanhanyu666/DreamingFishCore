"""僵尸指挥官的四组动画：行走 / 近战三段连招 / 射击 / 召唤（旗子插地）。

坐标与符号（这一节是踩了很久才定的，改之前先读完）
--------------------------------------------------
动画 JSON 的取值语义由原版 `KeyframeAnimations` 决定：

  * `degreeVec(x, y, z)` 是**恒等** —— JSON 里的旋转角直接就是 `ModelPart` 的
    `xRot/yRot/zRot`，也就是**原版 Java 模型语义**。
  * `posVec(x, y, z)` = `Vector3f(x, -y, z)` —— 只把 y 取反，x / z 原样。

所以下面这些数值全部按 **Java 模型语义**写（和写 `HumanoidModel` 时的心智模型一样）：

  * 肢体（手臂/腿，尖端在 +y）：**xRot 为负 = 向前摆**（原版僵尸前伸手臂、骑马伸腿都是负值）。
  * 躯干 / 头 / 帽（顶端在 -y）：**xRot 为正 = 前倾**，为负 = 后仰。
  * `yRot` 为正 = 转向模型的右侧；`zRot` 为正 = 肢体向模型右侧摆。
  * 位置通道：x / z 原样、y 原样（`posVec` 内部会替我们翻 y），单位像素。

导出就是**原样写出**，不做任何取反 —— 取反交给预览脚本（它要换回 Bedrock 坐标去摆模型）。

时间轴
------
`length` 秒、`timestamp` 秒；伤害/召唤的落点必须和 AI 对齐，见各动画上的注释。
"""

